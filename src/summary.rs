#[derive(Copy, Clone)]
pub struct PackageName<'a> {
    pub namespace: &'a str,
    pub name: &'a str,
    pub version: Option<&'a Version>,
}

#[derive(Clone)]
pub struct MyInterface<'a> {
    pub id: InterfaceId,
    pub key: &'a WorldKey,
    pub docs: Option<&'a str>,
}

pub struct MyFunction<'a> {
    pub kind: FunctionKind,
    pub interface: Option<MyInterface<'a>>,
    pub name: &'a str,
    pub docs: Option<&'a str>,
    pub params: &'a [Param],
    pub result: &'a Option<Type>,
    pub wit_kind: wit_parser::FunctionKind,
}

impl MyFunction<'_> {
    fn key(&self) -> WorldKey {
        if let Some(interface) = self.interface.as_ref() {
            // Use the stored key: inline world interfaces are keyed by name.
            interface.key.clone()
        } else {
            WorldKey::Name(self.name.into())
        }
    }
}

#[derive(Clone)]
pub struct InterfaceInfo<'a> {
    package: Option<PackageName<'a>>,
    name: &'a str,
    docs: Option<&'a str>,
    /// Fully-qualified WIT name, e.g. `foo:bar/baz@0.1.0`.
    wit_key: String,
}

