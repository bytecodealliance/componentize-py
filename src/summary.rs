/// Registry key for an exported resource; documented on `scope` in `init.wit`.
fn resource_scope(scope: &str, resource: &str) -> String {
    format!("{scope}#{resource}")
}

/// Python module for a WIT interface, e.g. `imports.wasi.http_v0_2.types`.
struct InterfaceName {
    /// Snake-cased path components, relative to `imports`/`exports`.
    path: Vec<String>,
    /// Unique flat alias (e.g. `wasi_http_v0_2_types`) used by generated code.
    flat: String,
}

impl InterfaceName {
    fn new(path: impl IntoIterator<Item = String>) -> Self {
        let path = path
            .into_iter()
            .map(|c| c.to_snake_case().escape())
            .collect::<Vec<_>>();
        let flat = path.join("_");

        Self { path, flat }
    }

    /// Accepts a plain name or a dotted path, used verbatim (callers validate).
    fn from_override(name: &str) -> Self {
        let path = name.split('.').map(str::to_owned).collect::<Vec<_>>();
        let flat = path.join("_");

        Self { path, flat }
    }

    fn dotted(&self) -> String {
        self.path.join(".")
    }

    fn parent(&self) -> Option<String> {
        (self.path.len() > 1).then(|| self.path[..self.path.len() - 1].join("."))
    }

    fn leaf(&self) -> &str {
        self.path.last().unwrap()
    }
}

struct NamedInterface {
    name: InterfaceName,
    key: String,
    overridden: bool,
}

pub fn is_python_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

